-- Το κοινό ημερολόγιο στοιχείων ενός playthrough (US-07).
-- Κάθε στοιχείο καταχωρίζεται μία φορά ανά playthrough: το μοναδικό κλειδί (playthrough_id, evidence_id) το
-- εγγυάται και όταν δύο παίκτες προσθέτουν το ίδιο στοιχείο ταυτόχρονα.
-- Το evidence_id είναι id στοιχείου του αρχείου της αποστολής (#26), όχι foreign key.
-- Η ώρα στο όνομα είναι μετά το V202611261800 (playthrough), γιατί ο πίνακας αναφέρεται στο playthrough.
create table journal_entry (
    id             bigint generated by default as identity primary key,
    playthrough_id bigint                   not null references playthrough (id) on delete cascade,
    evidence_id    varchar(100)             not null,
    added_by       bigint                   not null references player (id),
    added_at       timestamp with time zone not null,
    constraint journal_entry_playthrough_evidence_uk unique (playthrough_id, evidence_id)
);
