-- Ομάδες παικτών και μέλη τους (US-03, US-04).
-- Ο κωδικός πρόσκλησης είναι μοναδικός.
-- Ένας παίκτης εμφανίζεται μία φορά σε κάθε ομάδα: το μοναδικό κλειδί (team_id, player_id) το εγγυάται
-- και όταν το ίδιο αίτημα συμμετοχής φτάνει δύο φορές ταυτόχρονα.
create table team (
    id          bigint generated by default as identity primary key,
    name        varchar(40)              not null,
    invite_code varchar(8)               not null,
    creator_id  bigint                   not null references player (id),
    created_at  timestamp with time zone not null
);

create unique index team_invite_code_uk on team (invite_code);

create table team_membership (
    id        bigint generated by default as identity primary key,
    team_id   bigint                   not null references team (id) on delete cascade,
    player_id bigint                   not null references player (id),
    role      varchar(10)              not null check (role in ('CREATOR', 'MEMBER')),
    joined_at timestamp with time zone not null,
    constraint team_membership_team_player_uk unique (team_id, player_id)
);

create index team_membership_player_idx on team_membership (player_id);
