-- Παίκτες (US-01). Το όνομα είναι μοναδικό χωρίς διάκριση πεζών-κεφαλαίων.
-- Το μοναδικό index στο lower(username) εγγυάται τη μοναδικότητα και σε ταυτόχρονες εγγραφές.
-- Το token του cookie δεν αποθηκεύεται, μόνο το SHA-256 του (hex, 64 χαρακτήρες).
create table player (
    id         bigint generated by default as identity primary key,
    username   varchar(20)              not null,
    token_hash varchar(64)              not null,
    created_at timestamp with time zone not null
);

create unique index player_username_lower_uk on player (lower(username));
create unique index player_token_hash_uk on player (token_hash);
