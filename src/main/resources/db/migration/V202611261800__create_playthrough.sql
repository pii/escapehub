-- Playthroughs: ένα παιχνίδι μιας ομάδας σε μια αποστολή (US-06).
-- Η αποστολή είναι αρχείο (#26) και όχι πίνακας, οπότε το mission_id δεν είναι foreign key. Το mission_version
-- κρατά την έκδοση του αρχείου με την οποία ξεκίνησε το playthrough.
-- Το version είναι για optimistic locking (@Version), όταν το playthrough αλλάζει κατά το παιχνίδι.
-- Η ώρα στο όνομα είναι μετά το V202611261700 (team), γιατί ο πίνακας αναφέρεται στο team.
create table playthrough (
    id              bigint generated by default as identity primary key,
    team_id         bigint                   not null references team (id) on delete cascade,
    mission_id      varchar(100)             not null,
    mission_version integer                  not null,
    started_at      timestamp with time zone not null,
    completed_at    timestamp with time zone,
    version         bigint                   not null default 0
);

-- Το πολύ ένα ενεργό playthrough ανά ομάδα και αποστολή, και σε ταυτόχρονα αιτήματα έναρξης.
create unique index playthrough_active_uk on playthrough (team_id, mission_id) where completed_at is null;

create index playthrough_team_idx on playthrough (team_id);
